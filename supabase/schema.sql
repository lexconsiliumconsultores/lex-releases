-- ============ CLIENTES ============
CREATE TABLE IF NOT EXISTS clientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  cedula TEXT UNIQUE,
  telefono TEXT,
  email TEXT,
  direccion TEXT,
  fecha_registro TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- ============ CASOS ============
CREATE TABLE IF NOT EXISTS casos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_caso TEXT UNIQUE NOT NULL,
  titulo TEXT NOT NULL,
  cliente_id BIGINT REFERENCES clientes(id),
  tipo TEXT,
  estado TEXT DEFAULT 'Activo',
  descripcion TEXT,
  fecha_apertura TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  fecha_cierre TIMESTAMPTZ,
  abogado TEXT
);

-- ============ DOCUMENTOS ============
CREATE TABLE IF NOT EXISTS documentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  caso_id BIGINT REFERENCES casos(id),
  nombre TEXT NOT NULL,
  tipo TEXT,
  ruta TEXT,
  fecha_subida TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- ============ PLAZOS ============
CREATE TABLE IF NOT EXISTS plazos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  caso_id BIGINT REFERENCES casos(id),
  titulo TEXT NOT NULL,
  fecha_limite TIMESTAMPTZ,
  hora TEXT,
  estado TEXT DEFAULT 'Pendiente',
  notas TEXT,
  outlook_event_id TEXT
);

-- ============ SEGUIMIENTO ============
CREATE TABLE IF NOT EXISTS seguimiento (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  caso_id BIGINT REFERENCES casos(id),
  fecha TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  nota TEXT NOT NULL,
  autor TEXT
);

-- ============ FACTURAS ============
CREATE TABLE IF NOT EXISTS facturas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero BIGINT UNIQUE,
  caso_id BIGINT REFERENCES casos(id),
  cliente_id BIGINT REFERENCES clientes(id),
  concepto TEXT,
  monto NUMERIC(14,2) DEFAULT 0,
  estado TEXT DEFAULT 'Pendiente',
  fecha_emision TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  fecha_vencimiento TIMESTAMPTZ
);

-- ============ PAGOS ============
CREATE TABLE IF NOT EXISTS pagos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  factura_id BIGINT REFERENCES facturas(id),
  monto NUMERIC(14,2) NOT NULL,
  fecha TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  metodo TEXT,
  referencia TEXT
);

-- ============ DOCUMENTOS GENERADOS ============
CREATE TABLE IF NOT EXISTS documentos_generados (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo TEXT NOT NULL,
  tipo TEXT,
  caso_id BIGINT REFERENCES casos(id),
  contenido TEXT,
  fecha_creacion TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- ============ CONVERSACIONES CHAT ============
CREATE TABLE IF NOT EXISTS conversaciones_chat (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo TEXT NOT NULL,
  usuario TEXT,
  contenido TEXT,
  fecha_guardado TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- ============ NOTIFICACIONES ============
CREATE TABLE IF NOT EXISTS notificaciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  caso_id BIGINT REFERENCES casos(id),
  cliente_id BIGINT REFERENCES clientes(id),
  tipo TEXT NOT NULL,
  mensaje TEXT NOT NULL,
  telefono TEXT,
  email TEXT,
  asunto TEXT,
  canal TEXT,
  estado TEXT DEFAULT 'Enviado',
  fecha TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- ============ USUARIOS ============
CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario TEXT UNIQUE NOT NULL,
  nombre TEXT NOT NULL,
  password TEXT NOT NULL,
  rol TEXT DEFAULT 'asistente',
  activo INTEGER DEFAULT 1,
  fecha_creacion TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- ============ CONFIG (pares clave-valor) ============
CREATE TABLE IF NOT EXISTS config (
  clave TEXT PRIMARY KEY,
  valor TEXT
);

-- ============ INDICES ============
CREATE INDEX IF NOT EXISTS idx_casos_cliente ON casos(cliente_id);
CREATE INDEX IF NOT EXISTS idx_documentos_caso ON documentos(caso_id);
CREATE INDEX IF NOT EXISTS idx_plazos_caso ON plazos(caso_id);
CREATE INDEX IF NOT EXISTS idx_seguimiento_caso ON seguimiento(caso_id);
CREATE INDEX IF NOT EXISTS idx_facturas_caso ON facturas(caso_id);
CREATE INDEX IF NOT EXISTS idx_facturas_cliente ON facturas(cliente_id);
CREATE INDEX IF NOT EXISTS idx_pagos_factura ON pagos(factura_id);
CREATE INDEX IF NOT EXISTS idx_notificaciones_caso ON notificaciones(caso_id);
CREATE INDEX IF NOT EXISTS idx_notificaciones_cliente ON notificaciones(cliente_id);

