const wx = require('sql.js');
const fs = require('fs');
const dbPath = 'C:\\Users\\CASA\\AppData\\Roaming\\LEX\\lex.db';
const buffer = fs.readFileSync(dbPath);
const SQL = wx.default || wx;
const db = new SQL.Database(buffer);
const tables = db.exec("SELECT name FROM sqlite_master WHERE type='table'");
console.log('Tables exist:', tables[0] ? tables[0].values.map(r => r.name) : 'none');
const usersResult = db.exec("SELECT count(*) as cnt FROM usuarios");
console.log('Usuarios count:', usersResult[0] ? usersResult[0].values[0] : 'error');
const clientesResult = db.exec("SELECT count(*) as cnt FROM clientes");
console.log('Clientes count:', clientesResult[0] ? clientesResult[0].values[0] : 'error');
const casoCount = db.exec("SELECT count(*) as cnt FROM casos");
console.log('Casos count:', casoCount[0] ? casoCount[0].values[0] : 'error');
db.close();